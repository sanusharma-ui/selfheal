"""Generate notices from the locked local Cargo registry; never builds/downloads."""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def render(registry: Path) -> str:
    lock = tomllib.loads((ROOT / "Cargo.lock").read_text(encoding="utf-8"))
    sections = [
        "# Third-party notices\n\n"
        "SelfHeal's original source is MIT licensed; see LICENSE. Native wheels\n"
        "contain Rust dependencies under their own terms. This conservative\n"
        "inventory covers every registry dependency in Cargo.lock, including\n"
        "build-time and target-specific dependencies. For dual-licensed crates,\n"
        "MIT is selected when offered, retaining any additional Unicode terms;\n"
        "Apache-only crates retain their stated exceptions. Upstream notices and\n"
        "license texts are reproduced below without changing their terms.\n\n"
        "The Python dependencies python-dotenv, cloudpickle and optional pytest are separately\n"
        "installed distributions; their own license notices ship with them.\n"
        "No API keys, models or proprietary provider SDKs are distributed here.\n\n"
        "Generated by scripts/generate_notices.py from the locked registry.\n"
    ]
    for package in sorted(lock["package"], key=lambda item: item["name"]):
        if "source" not in package:
            continue
        if not package["source"].startswith("registry+"):
            raise ValueError("Non-registry dependencies need an explicit notice review")
        name, version = package["name"], package["version"]
        matches = sorted(registry.glob(f"*/{name}-{version}"))
        if len(matches) != 1:
            raise ValueError(f"Missing or ambiguous cached source: {name} {version}. Run cargo fetch --locked yourself.")
        source = matches[0]
        metadata = tomllib.loads((source / "Cargo.toml").read_text(encoding="utf-8"))["package"]
        expression = metadata.get("license", "")
        if not expression:
            raise ValueError(f"License metadata needs review: {name} {version}")
        notices = {path for path in source.iterdir() if path.is_file() and
                   path.name.lower().startswith(("license", "licence", "copying", "copyright", "notice", "authors"))}
        if metadata.get("license-file"):
            notices.add(source / metadata["license-file"])
        if not notices:
            raise ValueError(f"No upstream license text found: {name} {version}")
        sections.append(f"\n## {name} {version}\n\nDeclared license: `{expression}`.\n")
        for path in sorted(notices):
            text = path.read_text(encoding="utf-8").strip()
            sections.append(f"\n### {path.relative_to(source).as_posix()}\n\n````text\n{text}\n````\n")
    return "".join(sections)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare committed notices without writing")
    default = Path(os.environ.get("CARGO_HOME", str(Path.home() / ".cargo"))) / "registry" / "src"
    parser.add_argument("--registry", type=Path, default=default)
    args = parser.parse_args()
    try:
        content = render(args.registry)
        output = ROOT / "THIRD_PARTY_NOTICES.md"
        if args.check:
            if not output.exists() or output.read_text(encoding="utf-8") != content:
                raise ValueError("THIRD_PARTY_NOTICES.md does not match Cargo.lock; regenerate before release")
        else:
            output.write_text(content, encoding="utf-8", newline="\n")
    except (OSError, ValueError) as exc:
        print(f"Notice check stopped: {exc}")
        return 1
    print("Locked dependency notices verified." if args.check else "Locked dependency notices generated.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
